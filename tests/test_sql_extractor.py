@pytest.fixture()
def sql_project(tmp_path):
    """Create a sample SQL project structure for testing."""
    sql_dir = os.path.join(tmp_path, "sql")
    os.makedirs(sql_dir)

    # Main schema file with tables, comments, views, types, functions
    schema_sql = os.path.join(sql_dir, "schema.sql")
    with open(schema_sql, "w", encoding="utf-8") as f:
        f.write("""\
-- Main schema for the application

CREATE TABLE users (
    id uuid NOT NULL DEFAULT gen_random_uuid(),
    email text NOT NULL UNIQUE,
    display_name text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    is_active boolean NOT NULL DEFAULT true,
    PRIMARY KEY (id)
);

COMMENT ON TABLE users IS 'Registered user accounts';
COMMENT ON COLUMN users.id IS 'Unique user identifier';
COMMENT ON COLUMN users.email IS 'User email address, must be unique';
COMMENT ON COLUMN users.display_name IS 'Optional display name';

CREATE TABLE posts (
    id bigint GENERATED ALWAYS AS IDENTITY,
    author_id uuid NOT NULL REFERENCES users(id),
    title text NOT NULL,
    body text NOT NULL DEFAULT '',
    view_count integer NOT NULL DEFAULT 0,
    score numeric(10,2),
    tags text[],
    published_at timestamptz,
    CONSTRAINT posts_title_check CHECK (length(title) > 0)
);

COMMENT ON TABLE posts IS 'User-created blog posts';
COMMENT ON COLUMN posts.author_id IS 'Reference to the post author';
COMMENT ON COLUMN posts.tags IS 'Array of tag strings';

CREATE VIEW active_users AS
SELECT id, email, display_name
FROM users
WHERE is_active = true;

CREATE OR REPLACE VIEW recent_posts AS
SELECT p.id, p.title, u.display_name AS author
FROM posts p
JOIN users u ON u.id = p.author_id
WHERE p.published_at > now() - interval '7 days';

CREATE TYPE status_type AS ENUM ('draft', 'published', 'archived');

CREATE TYPE address AS (
    street text,
    city text,
    zip_code text,
    country text
);

CREATE OR REPLACE FUNCTION update_timestamp()
RETURNS trigger AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE FUNCTION soft_delete(target_id uuid)
RETURNS void AS $$
BEGIN
    UPDATE users SET is_active = false WHERE id = target_id;
END;
$$ LANGUAGE plpgsql;

COMMENT ON FUNCTION update_timestamp IS 'Auto-update timestamp trigger function';
""")

    # File with schema-qualified names
    qualified_sql = os.path.join(sql_dir, "qualified.sql")
    with open(qualified_sql, "w", encoding="utf-8") as f:
        f.write("""\
CREATE TABLE public.sessions (
    id uuid NOT NULL DEFAULT gen_random_uuid(),
    user_id uuid NOT NULL REFERENCES public.users(id),
    token text NOT NULL,
    expires_at timestamptz NOT NULL
);

COMMENT ON TABLE public.sessions IS 'Active user sessions';
COMMENT ON COLUMN public.sessions.token IS 'Session authentication token';

CREATE TABLE IF NOT EXISTS audit.events (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    event_type text NOT NULL,
    payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);
""")

    # File with generated columns
    generated_sql = os.path.join(sql_dir, "generated.sql")
    with open(generated_sql, "w", encoding="utf-8") as f:
        f.write("""\
CREATE TABLE products (
    id bigint GENERATED ALWAYS AS IDENTITY,
    name text NOT NULL,
    price numeric(10,2) NOT NULL,
    tax_rate numeric(5,4) NOT NULL DEFAULT 0.0825,
    total_price numeric(10,2) GENERATED ALWAYS AS (price * (1 + tax_rate)) STORED,
    sku text NOT NULL UNIQUE
);
""")

    # File with dollar-quoted and escaped comments
    comments_sql = os.path.join(sql_dir, "comments.sql")
    with open(comments_sql, "w", encoding="utf-8") as f:
        f.write("""\
CREATE TABLE items (
    id serial PRIMARY KEY,
    name text NOT NULL
);

COMMENT ON TABLE items IS $$Items in the user's inventory$$;
COMMENT ON COLUMN items.name IS $desc$Item display name (can't be empty)$desc$;
""")

    return tmp_path


