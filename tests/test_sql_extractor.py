        sql_file.write_text(
            "CREATE TABLE public.users (id serial);\n"
            "CREATE TABLE audit.events (id serial);\n",
            encoding="utf-8",
        )
        symbols = SqlExtractor().public_symbols(str(sql_file))
        assert "users" in symbols
        assert "events" in symbols

