class TestParseCreateTable:
    def test_basic_columns(self):
        source = """\
CREATE TABLE users (
    id uuid NOT NULL,
    name text,
    age integer NOT NULL DEFAULT 0
);
"""
        tables = _parse_create_table(source)
        assert len(tables) == 1
        t = tables[0]
        assert t["name"] == "users"
        assert t["schema"] == ""
        assert len(t["columns"]) == 3

        id_col = t["columns"][0]
        assert id_col["name"] == "id"
        assert id_col["type"] == "uuid"
        assert id_col["nullable"] is False

        name_col = t["columns"][1]
        assert name_col["name"] == "name"
        assert name_col["type"] == "text"
        assert name_col["nullable"] is True

        age_col = t["columns"][2]
        assert age_col["name"] == "age"
        assert age_col["type"] == "integer"
        assert age_col["nullable"] is False
        assert age_col["default"] == "0"

    def test_types_int_text_timestamptz_uuid(self):
        source = """\
CREATE TABLE t (
    a integer,
    b text,
    c timestamptz,
    d uuid
);
"""
        tables = _parse_create_table(source)
        cols = tables[0]["columns"]
        assert cols[0]["type"] == "integer"
        assert cols[1]["type"] == "text"
        assert cols[2]["type"] == "timestamptz"
        assert cols[3]["type"] == "uuid"

    def test_array_type(self):
        source = "CREATE TABLE t (tags text[], ids integer[]);\n"
        tables = _parse_create_table(source)
        cols = tables[0]["columns"]
        assert cols[0]["type"] == "text[]"
        assert cols[1]["type"] == "integer[]"

    def test_custom_type(self):
        source = "CREATE TABLE t (status status_type NOT NULL);\n"
        tables = _parse_create_table(source)
        cols = tables[0]["columns"]
        assert cols[0]["type"] == "status_type"

    def test_parameterized_type(self):
        source = "CREATE TABLE t (score numeric(10,2), label varchar(255));\n"
        tables = _parse_create_table(source)
        cols = tables[0]["columns"]
        assert cols[0]["type"] == "numeric(10,2)"
        assert cols[1]["type"] == "varchar(255)"

    def test_not_null(self):
        source = "CREATE TABLE t (a text NOT NULL, b text);\n"
        tables = _parse_create_table(source)
        cols = tables[0]["columns"]
        assert cols[0]["nullable"] is False
        assert cols[1]["nullable"] is True

    def test_default_value(self):
        source = """\
CREATE TABLE t (
    a text NOT NULL DEFAULT 'hello',
    b integer DEFAULT 42,
    c boolean NOT NULL DEFAULT true,
    d timestamptz DEFAULT now()
);
"""
        tables = _parse_create_table(source)
        cols = tables[0]["columns"]
        assert cols[0]["default"] == "'hello'"
        assert cols[1]["default"] == "42"
        assert cols[2]["default"] == "true"
        assert cols[3]["default"] == "now()"

    def test_generated_always_as_identity(self):
        source = "CREATE TABLE t (id bigint GENERATED ALWAYS AS IDENTITY);\n"
        tables = _parse_create_table(source)
        cols = tables[0]["columns"]
        assert "GENERATED ALWAYS AS IDENTITY" in cols[0]["default"]

    def test_generated_by_default_as_identity(self):
        source = "CREATE TABLE t (id bigint GENERATED BY DEFAULT AS IDENTITY);\n"
        tables = _parse_create_table(source)
        cols = tables[0]["columns"]
        assert "GENERATED BY DEFAULT AS IDENTITY" in cols[0]["default"]

    def test_generated_stored(self):
        source = """\
CREATE TABLE t (
    price numeric(10,2) NOT NULL,
    tax numeric(10,2) NOT NULL,
    total numeric(10,2) GENERATED ALWAYS AS (price + tax) STORED
);
"""
        tables = _parse_create_table(source)
        cols = tables[0]["columns"]
        total_col = cols[2]
        assert "GENERATED ALWAYS AS" in total_col["default"]
        assert "STORED" in total_col["default"]

    def test_inline_primary_key(self):
        source = "CREATE TABLE t (id serial PRIMARY KEY, name text);\n"
        tables = _parse_create_table(source)
        cols = tables[0]["columns"]
        assert "PRIMARY KEY" in cols[0]["constraints"]

    def test_inline_unique(self):
        source = "CREATE TABLE t (email text UNIQUE);\n"
        tables = _parse_create_table(source)
        cols = tables[0]["columns"]
        assert "UNIQUE" in cols[0]["constraints"]

    def test_inline_references(self):
        source = "CREATE TABLE t (user_id uuid REFERENCES users(id));\n"
        tables = _parse_create_table(source)
        cols = tables[0]["columns"]
        ref = [c for c in cols[0]["constraints"] if c.startswith("REFERENCES")]
        assert len(ref) == 1
        assert "users(id)" in ref[0]

    def test_table_level_constraints_skipped(self):
        source = """\
CREATE TABLE t (
    id serial,
    name text,
    PRIMARY KEY (id),
    UNIQUE (name),
    CHECK (length(name) > 0)
);
"""
        tables = _parse_create_table(source)
        cols = tables[0]["columns"]
        # Only id and name should be columns, not the constraints
        assert len(cols) == 2
        assert cols[0]["name"] == "id"
        assert cols[1]["name"] == "name"

    def test_schema_qualified_table(self):
        source = "CREATE TABLE public.users (id serial);\n"
        tables = _parse_create_table(source)
        assert tables[0]["name"] == "users"
        assert tables[0]["schema"] == "public"

    def test_if_not_exists(self):
        source = "CREATE TABLE IF NOT EXISTS events (id serial);\n"
        tables = _parse_create_table(source)
        assert tables[0]["name"] == "events"

    def test_default_with_type_cast(self):
        source = "CREATE TABLE t (data jsonb NOT NULL DEFAULT '{}'::jsonb);\n"
        tables = _parse_create_table(source)
        cols = tables[0]["columns"]
        assert "::jsonb" in cols[0]["default"]


