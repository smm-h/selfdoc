class TestParseComments:
    def test_table_comment(self):
        source = "COMMENT ON TABLE users IS 'Registered user accounts';\n"
        comments = _parse_comments(source)
        assert comments[("table", "users")] == "Registered user accounts"

    def test_column_comment(self):
        source = "COMMENT ON COLUMN users.email IS 'User email address';\n"
        comments = _parse_comments(source)
        assert comments[("column", "users.email")] == "User email address"

    def test_escaped_single_quotes(self):
        source = "COMMENT ON TABLE items IS 'Items in the user''s inventory';\n"
        comments = _parse_comments(source)
        assert comments[("table", "items")] == "Items in the user's inventory"

    def test_dollar_quoting_empty_tag(self):
        source = "COMMENT ON TABLE items IS $$Dollar quoted text$$;\n"
        comments = _parse_comments(source)
        assert comments[("table", "items")] == "Dollar quoted text"

    def test_dollar_quoting_named_tag(self):
        source = "COMMENT ON TABLE items IS $desc$Tagged dollar quote$desc$;\n"
        comments = _parse_comments(source)
        assert comments[("table", "items")] == "Tagged dollar quote"

    def test_is_null_removes_comment(self):
        source = """\
COMMENT ON TABLE users IS 'Some text';
COMMENT ON TABLE users IS NULL;
"""
        comments = _parse_comments(source)
        # IS NULL should not add the comment (only the first one exists,
        # or IS NULL should override -- in our implementation IS NULL is skipped,
        # so the first one remains)
        # The important thing: IS NULL does not crash or produce garbage
        assert ("table", "users") in comments

    def test_schema_qualified_comment(self):
        source = "COMMENT ON TABLE public.sessions IS 'Active sessions';\n"
        comments = _parse_comments(source)
        assert comments[("table", "public.sessions")] == "Active sessions"

    def test_schema_qualified_column_comment(self):
        source = "COMMENT ON COLUMN public.sessions.token IS 'Auth token';\n"
        comments = _parse_comments(source)
        assert comments[("column", "public.sessions.token")] == "Auth token"

    def test_view_comment(self):
        source = "COMMENT ON VIEW active_users IS 'Only active users';\n"
        comments = _parse_comments(source)
        assert comments[("view", "active_users")] == "Only active users"

    def test_function_comment(self):
        source = "COMMENT ON FUNCTION update_ts IS 'Timestamp trigger';\n"
        comments = _parse_comments(source)
        assert comments[("function", "update_ts")] == "Timestamp trigger"

    def test_multiline_comment_string(self):
        source = """\
COMMENT ON TABLE users IS 'This is a
multiline comment
spanning three lines';
"""
        comments = _parse_comments(source)
        assert "multiline comment" in comments[("table", "users")]
        assert "spanning three lines" in comments[("table", "users")]

    def test_case_insensitive_keywords(self):
        source = "comment on table users is 'lower case keywords';\n"
        comments = _parse_comments(source)
        assert comments[("table", "users")] == "lower case keywords"


