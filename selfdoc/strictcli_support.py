#: The one dumped-schema format this reader understands.  strictcli 0.41.0
#: writes it; there is no v1 path and no negotiated fallback.
SUPPORTED_SCHEMA_VERSION = 2


def read_schema_json(base_dir, source_paths=None):
    """Read ``.strictcli/schema.json`` and translate to the internal format.

    Returns a dict with ``app_name``, ``app_version``, ``app_help``,
    ``global_flags`` (list), ``infra`` (dict), ``deprecated`` (dict),
    ``config`` (dict of the app-level config declaration), ``commands``
    (list), and ``groups`` (list) -- or ``None`` if the schema file does not
    exist.

    The translation preserves every per-entry field the renderers read
    (``value_schema``, ``presence``, ``default``, ``choices``, ``elect_by``,
    ``nullable``, ``negatable``, ``unique``, ``prefixed``, ``variadic``,
    ``hidden``, ``deprecated``, ``passthrough``, ``flag_sets``,
    ``constraints``, ``update_of``, ``write_mode``) plus the effects-regime
    per-command fields (``effect``, ``consequential``, ``grants``,
    ``dry_run_supported``, ``dry_run_unsupported_reason``), all untouched.

    strictcli omits the app-level ``global_flags``/``infra``/``deprecated``
    keys when they are empty, and some emitters write an explicit ``null``;
    both normalize to empty containers so renderers can truth-test them.

    Raises:
        ValueError: When the file declares a ``schema_version`` other than
            :data:`SUPPORTED_SCHEMA_VERSION`, or carries no ``project_id``,
            or names a different project.
    """
    schema_path = os.path.join(base_dir, ".strictcli", "schema.json")
    if not os.path.isfile(schema_path):
        return None

    with open(schema_path, "r", encoding="utf-8") as f:
        schema = json.load(f)

    # The version is read before anything else: every key below is read on
    # v2's terms, and reading a v1 document with them produces a page that
    # is wrong without being empty.
    version = schema.get("schema_version")
    if version != SUPPORTED_SCHEMA_VERSION:
        app_name = schema.get("name", "<app>")
        raise ValueError(
            f"Schema at {schema_path} declares schema_version "
            f"{version!r}; this selfdoc reads schema_version "
            f"{SUPPORTED_SCHEMA_VERSION} only. Regenerate it with a "
            f"strictcli >= 0.41.0: {app_name} --dump-schema"
        )

    # Validate project_id
    project_id = schema.get("project_id")
    if project_id is None:
        app_name = schema.get("name", "<app>")
        raise ValueError(
            f"Schema missing project_id field. "
            f"Regenerate with: {app_name} --dump-schema"
        )
    expected = _read_project_field(base_dir, "name")
    if expected != "unknown" and project_id != expected:
        raise ValueError(
            f"Schema project_id '{project_id}' does not match "
            f"project name '{expected}'. Wrong schema file?"
        )

    result = {
        "app_name": schema.get("name", ""),
        "app_version": schema.get("version", ""),
        "app_help": schema.get("help", ""),
        "global_flags": schema.get("global_flags") or [],
        "infra": schema.get("infra") or {},
        "deprecated": schema.get("deprecated") or {},
        # v2's behavioral-completeness keys.  Each is emitted exactly when
        # the app departs from the framework's own behaviour, so their
        # presence is the whole reason to document them.
        "config": schema.get("config") or False,
        "config_format": schema.get("config_format"),
        "config_path": schema.get("config_path"),
        "config_conflict_mode": schema.get("config_conflict_mode"),
        "env_prefix": schema.get("env_prefix"),
    }

    # Translate commands dict -> list
    commands_dict = schema.get("commands", {})
    result["commands"] = [
        _translate_command(name, cmd)
        for name, cmd in commands_dict.items()
    ]

    # Translate groups dict -> list (with nested commands dict -> list)
    groups_dict = schema.get("groups", {})
    result["groups"] = [
        _translate_group(name, grp)
        for name, grp in groups_dict.items()
    ]

    return result


def _translate_command(name, cmd):
    """Translate a schema command dict to the internal format."""
    translated = dict(cmd)
    # Ensure name is present
    translated.setdefault("name", name)
    return translated


def _translate_group(name, grp):
    """Translate a schema group dict to the internal format."""
    translated = {
        "name": grp.get("name", name),
        "help": grp.get("help", ""),
    }

    # Convert nested commands dict -> list
    commands_dict = grp.get("commands", {})
    translated["commands"] = [
        _translate_command(cname, cmd)
        for cname, cmd in commands_dict.items()
    ]

    # Preserve extra fields
    for key in ("deprecated", "groups"):
        if key in grp:
            translated[key] = grp[key]

    return translated


