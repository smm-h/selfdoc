def expected_cli_page_filenames(cli_structure):
    """Return the list of filenames ``generate_cli_pages`` would write.

    Used by the stale-file cleanup pass to know which CLI page names are
    "current" so the generated pages from a prior run are not deleted as
    stale before the new pages have been written.
    """
    if cli_structure is None:
        return []
    names = ["cli-index.md"]
    for cmd in cli_structure.get("commands", []):
        names.append(f"cli-{cmd['name']}.md")
    for grp in cli_structure.get("groups", []):
        names.append(f"cli-{grp['name']}.md")
    return names


def _read_existing_cli_description(filepath, *, kind, name, app_name,
                                  help_text=None):
    """Return the hand-edited ``description`` from a CLI page, else ``None``.

    Returns ``None`` (meaning: reseed with the machine default) if the file
    does not exist, has no ``description`` key, has an empty description, or
    still holds a machine-generated default (recognized by
    :func:`is_default_cli_description`).  Any other value is a genuine hand
    edit and is returned verbatim.
    """
    try:
        with open(filepath, "r", encoding="utf-8") as f:
            content = f.read()
    except OSError:
        return None

    metadata, _ = _parse_frontmatter(content)
    raw = metadata.get("description")
    if raw is None or not isinstance(raw, str):
        return None

    value = _normalize_cli_description(raw)
    if not value:
        return None

    if is_default_cli_description(
        value, kind=kind, name=name, app_name=app_name, help_text=help_text,
    ):
        return None

    return value


def generate_cli_pages(cli_structure, docs_dir):
    """Generate Markdown documentation pages from *cli_structure*.

    Creates an index page and one page per top-level command group.
    All pages have ``generated: true`` frontmatter and read-only
    permissions (0o444).

    Returns a list of generated filenames (relative to *docs_dir*).
    """
    effects.makedirs(docs_dir, exist_ok=True)
    generated = []

    app_name = cli_structure.get("app_name", "")
    app_help = cli_structure.get("app_help", "")
    app_version = cli_structure.get("app_version", "")
    commands = cli_structure.get("commands", [])
    groups = cli_structure.get("groups", [])

    # -- Index page --
    default_index_desc = compute_default_cli_description(
        "index", None, app_name, None,
    )
    index_path = os.path.join(docs_dir, "cli-index.md")
    existing_index_desc = _read_existing_cli_description(
        index_path, kind="index", name=None, app_name=app_name,
    )
    cli_index_desc = (
        existing_index_desc
        if existing_index_desc is not None
        else default_index_desc
    )
    seeded_index = "seeded: true" if existing_index_desc is None else ""
    index_lines = [
        "---",
        f"title: {app_name} CLI Reference",
        f'description: "{cli_index_desc}"',
        "generated: true",
    ]
    if seeded_index:
        index_lines.append(seeded_index)
    index_lines.extend([
        'nav_group: "CLI Reference"',
        "nav_order: 0",
        "order: 91",
        "---",
        "<!-- generated by selfdoc gen (strictcli), do not edit -->",
        "",
        f"# {app_name} CLI Reference",
        "",
    ])
    if app_help:
        index_lines.append(app_help)
        index_lines.append("")
    if app_version:
        # A var DIRECTIVE, not the literal version: the raw page body is what
        # staleness hashes, so baking the version in here moved the content
        # hash on every release and tripped STALE001 with zero signal.  The
        # directive resolves at build time, so the site still shows the
        # current version.
        index_lines.append('Version: :-: var key="project.version"')
        index_lines.append("")

    if commands:
        index_lines.append("## Commands")
        index_lines.append("")
        for cmd in commands:
            fname = f"cli-{cmd['name']}.html"
            index_lines.append(f"- [{cmd['name']}]({fname}) -- {cmd.get('help', '')}")
        index_lines.append("")

    if groups:
        index_lines.append("## Command Groups")
        index_lines.append("")
        for grp in groups:
            fname = f"cli-{grp['name']}.html"
            index_lines.append(f"- [{grp['name']}]({fname}) -- {grp.get('help', '')}")
        index_lines.append("")

    index_filename = "cli-index.md"
    _write_page(
        os.path.join(docs_dir, index_filename),
        "\n".join(index_lines),
    )
    generated.append(index_filename)

    # Build alphabetical ordering for all command/group pages
    all_names = sorted(
        [cmd["name"] for cmd in commands] + [grp["name"] for grp in groups]
    )
    name_to_nav_order = {name: idx + 1 for idx, name in enumerate(all_names)}

    # -- One page per top-level command --
    for cmd in commands:
        fname = f"cli-{cmd['name']}.md"
        out_path = os.path.join(docs_dir, fname)
        content = _render_command_page(
            cmd, app_name, name_to_nav_order[cmd["name"]],
            existing_path=out_path,
        )
        _write_page(out_path, content)
        generated.append(fname)

    # -- One page per group --
    for grp in groups:
        fname = f"cli-{grp['name']}.md"
        out_path = os.path.join(docs_dir, fname)
        content = _render_group_page(
            grp, app_name, name_to_nav_order[grp["name"]],
            existing_path=out_path,
        )
        _write_page(out_path, content)
        generated.append(fname)

    return generated


def _write_page(filepath, content):
    """Write a generated page atomically with read-only permissions."""
    _atomic_write(filepath, content, permissions=0o444)


def _render_command_page(cmd, app_name, nav_order, existing_path=None):
    """Render a Markdown page for a single command.

    If *existing_path* points to an existing page whose ``description``
    frontmatter has been hand-edited (i.e. is neither the current default
    -- the complete first sentence of the help -- nor a historical
    ``help[:155]`` truncation nor the long-form default template), that
    description is preserved instead of recomputing it.
    """
    name = cmd["name"]
    chelp = cmd.get("help", "")
    flags = cmd.get("flags", [])
    args = cmd.get("args", [])

    default_desc = compute_default_cli_description(
        "command", name, app_name, chelp,
    )

    existing_desc = None
    if existing_path is not None:
        existing_desc = _read_existing_cli_description(
            existing_path, kind="command", name=name, app_name=app_name,
            help_text=chelp,
        )
    cmd_desc = existing_desc if existing_desc is not None else default_desc
    seeded = existing_desc is None
    lines = [
        "---",
        f"title: {app_name} {name}",
        f'description: "{cmd_desc}"',
        "generated: true",
    ]
    if seeded:
        lines.append("seeded: true")
    lines.extend([
        'nav_group: "CLI Reference"',
        f"nav_order: {nav_order}",
        "---",
        "<!-- generated by selfdoc gen (strictcli), do not edit -->",
        "",
        f"# {app_name} {name}",
        "",
    ])
    if chelp:
        lines.append(chelp)
        lines.append("")

    if flags:
        lines.append("## Flags")
        lines.append("")
        flag_rows = []
        for fl in flags:
            short = fl.get("short") or ""
            ftype = fl.get("type", "str")
            default = fl.get("default") or ""
            env = fl.get("env") or ""
            desc = fl.get("help", "")
            flag_rows.append([
                f"`--{fl['name']}`", _fmt_short(short), ftype, default, env, desc,
            ])
        lines.append(render_markdown_table(
            ["Name", "Short", "Type", "Default", "Env", "Description"],
            flag_rows,
        ))
        lines.append("")

    if args:
        lines.append("## Arguments")
        lines.append("")
        arg_rows = []
        for ar in args:
            req = "yes" if ar.get("required", True) else "no"
            arg_rows.append([f"`{ar['name']}`", req, ar.get("help", "")])
        lines.append(render_markdown_table(
            ["Name", "Required", "Description"],
            arg_rows,
        ))
        lines.append("")

    return "\n".join(lines)


def _render_group_page(grp, app_name, nav_order, existing_path=None):
    """Render a Markdown page for a command group and its subcommands.

    If *existing_path* points to an existing page whose ``description``
    frontmatter has been hand-edited (i.e. is neither the current default
    -- the complete first sentence of the help -- nor a historical
    ``help[:155]`` truncation nor the long-form default template), that
    description is preserved instead of recomputing it.
    """
    gname = grp["name"]
    ghelp = grp.get("help", "")
    subcmds = grp.get("commands", [])

    default_desc = compute_default_cli_description(
        "group", gname, app_name, ghelp,
    )

    existing_desc = None
    if existing_path is not None:
        existing_desc = _read_existing_cli_description(
            existing_path, kind="group", name=gname, app_name=app_name,
            help_text=ghelp,
        )
    grp_desc = existing_desc if existing_desc is not None else default_desc
    seeded = existing_desc is None
    lines = [
        "---",
        f"title: {app_name} {gname}",
        f'description: "{grp_desc}"',
        "generated: true",
    ]
    if seeded:
        lines.append("seeded: true")
    lines.extend([
        'nav_group: "CLI Reference"',
        f"nav_order: {nav_order}",
        "---",
        "<!-- generated by selfdoc gen (strictcli), do not edit -->",
        "",
        f"# {app_name} {gname}",
        "",
    ])
    if ghelp:
        lines.append(ghelp)
        lines.append("")

    for cmd in subcmds:
        cname = cmd["name"]
        chelp = cmd.get("help", "")
        flags = cmd.get("flags", [])
        args = cmd.get("args", [])

        lines.append(f"## {gname} {cname}")
        lines.append("")
        if chelp:
            lines.append(chelp)
            lines.append("")

        if flags:
            lines.append("### Flags")
            lines.append("")
            flag_rows = []
            for fl in flags:
                short = fl.get("short") or ""
                ftype = fl.get("type", "str")
                default = fl.get("default") or ""
                env = fl.get("env") or ""
                desc = fl.get("help", "")
                flag_rows.append([
                    f"`--{fl['name']}`", _fmt_short(short), ftype, default, env, desc,
                ])
            lines.append(render_markdown_table(
                ["Name", "Short", "Type", "Default", "Env", "Description"],
                flag_rows,
            ))
            lines.append("")

        if args:
            lines.append("### Arguments")
            lines.append("")
            arg_rows = []
            for ar in args:
                req = "yes" if ar.get("required", True) else "no"
                arg_rows.append([f"`{ar['name']}`", req, ar.get("help", "")])
            lines.append(render_markdown_table(
                ["Name", "Required", "Description"],
                arg_rows,
            ))
            lines.append("")

    return "\n".join(lines)


def _fmt_short(short):
    """Format a short flag for table display."""
    if short:
        return f"`-{short}`"
    return ""
