def uses_strictcli(source_paths, base_dir):
    """Return True if the project has a ``.strictcli/schema.json`` file.

    The *source_paths* parameter is accepted for call-site compatibility
    but is not used -- detection is purely based on the schema file.
    """
    schema_path = os.path.join(base_dir, ".strictcli", "schema.json")
    return os.path.isfile(schema_path)


# ---------------------------------------------------------------------------
# Schema discovery
# ---------------------------------------------------------------------------


class SchemaDiscoveryError(RuntimeError):
    """Raised when ``.strictcli/schema.json`` discovery fails or is ambiguous.

    A hard error (exit 1). Subclasses ``RuntimeError`` so the CLI's existing
    ``RuntimeError`` handlers surface it with a clean message and non-zero exit.
    """


# Directory names never traversed when discovering schemas. Hidden directories
# (leading ``.``) are pruned separately -- ``.strictcli`` is not traversed into
# but is still detected as a schema *location* under each visited directory.
_SCHEMA_DISCOVERY_EXCLUDES: set[str] = {
    "node_modules", "dist", "build", "_build", "target",
    "vendor", "venv", "__pycache__",
}


def discover_schema_dirs(base_dir):
    """Discover directories containing a ``.strictcli/schema.json`` file.

    Walks *base_dir*, pruning vendored/build directories and hidden
    directories (leading ``.``). For every visited directory, checks whether it
    holds a ``.strictcli/schema.json`` and records its path relative to
    *base_dir* (the project root uses ``"."``).

    Returns a sorted list of relative directory paths (each is the directory
    that *contains* the ``.strictcli`` folder, i.e. the value a ``schema-dir``
    attribute would take).
    """
    base_dir = os.path.abspath(base_dir)
    found = []
    for dirpath, dirnames, _filenames in os.walk(base_dir):
        # Prune traversal into vendored/build and hidden directories.
        dirnames[:] = [
            d for d in dirnames
            if d not in _SCHEMA_DISCOVERY_EXCLUDES and not d.startswith(".")
        ]
        schema_path = os.path.join(dirpath, ".strictcli", "schema.json")
        if os.path.isfile(schema_path):
            rel = os.path.relpath(dirpath, base_dir)
            found.append("." if rel == os.curdir else rel)
    return sorted(found)


# ---------------------------------------------------------------------------
# Schema reader
# ---------------------------------------------------------------------------


def read_schema_json(base_dir, source_paths=None):
    """Read ``.strictcli/schema.json`` and translate to the internal format.

    Returns a dict with ``app_name``, ``app_version``, ``app_help``,
    ``commands`` (list), and ``groups`` (list) -- or ``None`` if the
    schema file does not exist.

    The translation preserves new fields from the schema (``choices``,
    ``hidden``, ``deprecated``, ``variadic``, ``passthrough``,
    ``repeatable``, ``negatable``) so downstream consumers can use them.
    """
    schema_path = os.path.join(base_dir, ".strictcli", "schema.json")
    if not os.path.isfile(schema_path):
        return None

    with open(schema_path, "r", encoding="utf-8") as f:
        schema = json.load(f)

    # Validate project_id
    project_id = schema.get("project_id")
    if project_id is None:
        app_name = schema.get("name", "<app>")
        raise ValueError(
            f"Schema missing project_id field. "
            f"Regenerate with: {app_name} --dump-schema"
        )
    expected = _read_project_field(base_dir, "name")
    if expected != "unknown" and project_id != expected:
        raise ValueError(
            f"Schema project_id '{project_id}' does not match "
            f"project name '{expected}'. Wrong schema file?"
        )

    result = {
        "app_name": schema.get("name", ""),
        "app_version": schema.get("version", ""),
        "app_help": schema.get("help", ""),
    }

    # Translate commands dict -> list
    commands_dict = schema.get("commands", {})
    result["commands"] = [
        _translate_command(name, cmd)
        for name, cmd in commands_dict.items()
    ]

    # Translate groups dict -> list (with nested commands dict -> list)
    groups_dict = schema.get("groups", {})
    result["groups"] = [
        _translate_group(name, grp)
        for name, grp in groups_dict.items()
    ]

    return result


def _translate_command(name, cmd):
    """Translate a schema command dict to the internal format."""
    translated = dict(cmd)
    # Ensure name is present
    translated.setdefault("name", name)
    return translated


def _translate_group(name, grp):
    """Translate a schema group dict to the internal format."""
    translated = {
        "name": grp.get("name", name),
        "help": grp.get("help", ""),
    }

    # Convert nested commands dict -> list
    commands_dict = grp.get("commands", {})
    translated["commands"] = [
        _translate_command(cname, cmd)
        for cname, cmd in commands_dict.items()
    ]

    # Preserve extra fields
    for key in ("deprecated", "groups"):
        if key in grp:
            translated[key] = grp[key]

    return translated


