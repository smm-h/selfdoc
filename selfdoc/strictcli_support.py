def extract_cli_structure(source_paths, base_dir):
    """Read the CLI structure from ``.strictcli/schema.json``.

    Returns a dict describing the app, its commands, flags, args, and
    groups -- or raises ``FileNotFoundError`` if no schema is found.

    The *source_paths* parameter is accepted for call-site compatibility
    but is not used.
    """
    result = read_schema_json(base_dir, source_paths=source_paths)
    if result is not None:
        return result
    raise FileNotFoundError(
        "No .strictcli/schema.json found in "
        f"{base_dir!r}. Run '<app> --dump-schema' to generate it."
    )


