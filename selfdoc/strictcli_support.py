def expected_cli_page_filenames(cli_structure):
    """Return the list of filenames ``generate_cli_pages`` would write.

    Used by the stale-file cleanup pass to know which CLI page names are
    "current" so the generated pages from a prior run are not deleted as
    stale before the new pages have been written.
    """
    if cli_structure is None:
        return []
    names = ["cli-index.md"]
    for cmd in cli_structure.get("commands", []):
        names.append(f"cli-{cmd['name']}.md")
    for grp in cli_structure.get("groups", []):
        names.append(f"cli-{grp['name']}.md")
    return names


def _read_existing_cli_description(filepath, *, kind, name, app_name,
                                  help_text=None):
    """Return the hand-edited ``description`` from a CLI page, else ``None``.

    Returns ``None`` (meaning: reseed with the machine default) if the file
    does not exist, has no ``description`` key, has an empty description, or
    still holds a machine-generated default (recognized by
    :func:`is_default_cli_description`).  Any other value is a genuine hand
    edit and is returned verbatim.
    """
    try:
        with open(filepath, "r", encoding="utf-8") as f:
            content = f.read()
    except OSError:
        return None

    metadata, _ = _parse_frontmatter(content)
    raw = metadata.get("description")
    if raw is None or not isinstance(raw, str):
        return None

    value = _normalize_cli_description(raw)
    if not value:
        return None

    if is_default_cli_description(
        value, kind=kind, name=name, app_name=app_name, help_text=help_text,
    ):
        return None

    return value


def generate_cli_pages(cli_structure, docs_dir):
    """Generate Markdown documentation pages from *cli_structure*.

    Creates an index page and one page per top-level command group.
    All pages have ``generated: true`` frontmatter and read-only
    permissions (0o444).

    Returns a list of generated filenames (relative to *docs_dir*).
    """
    effects.makedirs(docs_dir, exist_ok=True)
    generated = []

    app_name = cli_structure.get("app_name", "")
    app_help = cli_structure.get("app_help", "")
    app_version = cli_structure.get("app_version", "")
    commands = cli_structure.get("commands", [])
    groups = cli_structure.get("groups", [])

    # -- Index page --
    default_index_desc = compute_default_cli_description(
        "index", None, app_name, None,
    )
    index_path = os.path.join(docs_dir, "cli-index.md")
    existing_index_desc = _read_existing_cli_description(
        index_path, kind="index", name=None, app_name=app_name,
    )
    cli_index_desc = (
        existing_index_desc
        if existing_index_desc is not None
        else default_index_desc
    )
    seeded_index = "seeded: true" if existing_index_desc is None else ""
    index_lines = [
        "---",
        f"title: {app_name} CLI Reference",
        f'description: "{cli_index_desc}"',
        "generated: true",
    ]
    if seeded_index:
        index_lines.append(seeded_index)
    index_lines.extend([
        'nav_group: "CLI Reference"',
        "nav_order: 0",
        "order: 91",
        "---",
        "<!-- generated by selfdoc gen (strictcli), do not edit -->",
        "",
        f"# {app_name} CLI Reference",
        "",
    ])
    if app_help:
        index_lines.append(app_help)
        index_lines.append("")
    if app_version:
        # A var DIRECTIVE, not the literal version: the raw page body is what
        # staleness hashes, so baking the version in here moved the content
        # hash on every release and tripped STALE001 with zero signal.  The
        # directive resolves at build time, so the site still shows the
        # current version.
        index_lines.append('Version: :-: var key="project.version"')
        index_lines.append("")

    if commands:
        index_lines.append("## Commands")
        index_lines.append("")
        for cmd in commands:
            href = root_page_link(f"cli-{cmd['name']}.md")
            index_lines.append(f"- [{cmd['name']}]({href}) -- {cmd.get('help', '')}")
        index_lines.append("")

    if groups:
        index_lines.append("## Command Groups")
        index_lines.append("")
        for grp in groups:
            href = root_page_link(f"cli-{grp['name']}.md")
            index_lines.append(f"- [{grp['name']}]({href}) -- {grp.get('help', '')}")
        index_lines.append("")

    global_flags = cli_structure.get("global_flags") or []
    if global_flags:
        index_lines.append("## Global flags")
        index_lines.append("")
        index_lines.append(_flag_table(global_flags))
        index_lines.append("")

    if _schema_has_effects(cli_structure):
        index_lines.append("## Framework flags")
        index_lines.append("")
        index_lines.append(_RESERVED_QUARTET_INTRO)
        index_lines.append("")
        index_lines.append(render_markdown_table(
            ["Flag", "Effect"], _RESERVED_QUARTET_ROWS,
        ))
        index_lines.append("")

    index_lines.extend(_config_lines(cli_structure))

    infra = cli_structure.get("infra") or {}
    if infra:
        index_lines.append("## Infrastructure")
        index_lines.append("")
        roots = infra.get("roots") or []
        if roots:
            index_lines.append("### Roots")
            index_lines.append("")
            index_lines.append(_env_table(roots, "Default"))
            index_lines.append("")
        handshakes = infra.get("handshakes") or []
        if handshakes:
            index_lines.append("### Handshake variables")
            index_lines.append("")
            index_lines.append(_env_table(handshakes, "Description"))
            index_lines.append("")
        connections = infra.get("connections") or []
        if connections:
            index_lines.append("### Connection variables")
            index_lines.append("")
            index_lines.append(_env_table(connections, "Description"))
            index_lines.append("")

    deprecated = cli_structure.get("deprecated") or {}
    if deprecated:
        index_lines.append("## Deprecated")
        index_lines.append("")
        for dname in sorted(deprecated):
            index_lines.append(f"- `{dname}` -- {deprecated[dname]}")
        index_lines.append("")

    index_filename = "cli-index.md"
    _write_page(
        os.path.join(docs_dir, index_filename),
        "\n".join(index_lines),
    )
    generated.append(index_filename)

    # Build alphabetical ordering for all command/group pages
    all_names = sorted(
        [cmd["name"] for cmd in commands] + [grp["name"] for grp in groups]
    )
    name_to_nav_order = {name: idx + 1 for idx, name in enumerate(all_names)}

    # -- One page per top-level command --
    for cmd in commands:
        fname = f"cli-{cmd['name']}.md"
        out_path = os.path.join(docs_dir, fname)
        content = _render_command_page(
            cmd, app_name, name_to_nav_order[cmd["name"]],
            existing_path=out_path,
        )
        _write_page(out_path, content)
        generated.append(fname)

    # -- One page per group --
    for grp in groups:
        fname = f"cli-{grp['name']}.md"
        out_path = os.path.join(docs_dir, fname)
        content = _render_group_page(
            grp, app_name, name_to_nav_order[grp["name"]],
            existing_path=out_path,
        )
        _write_page(out_path, content)
        generated.append(fname)

    return generated


def _write_page(filepath, content):
    """Write a generated page atomically with read-only permissions."""
    _atomic_write(filepath, content, permissions=0o444)


